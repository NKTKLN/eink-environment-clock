def latin_glyphs():
    src = (SRC / "epd_font5x7.h").read_text()
    out = {}
    for m in re.finditer(r"\{ ((?:0x[0-9A-F]{2}, ){4}0x[0-9A-F]{2}) \}, /\* (.) \*/", src):
        out[m.group(2)] = [int(x, 16) for x in m.group(1).split(", ")]
    return out


def columns(rows):
    assert len(rows) == 8 and all(len(r) == 5 for r in rows), rows
    return [sum(1 << y for y in range(8) if rows[y][x] == "#") for x in range(5)]


def parse(block, latin):
    out = []
    for line in block.strip().splitlines():
        ch, art = line.split(" ", 1)
        cols = latin[art] if len(art) == 1 else columns(art.split("|"))
        out.append((ch, cols))
    return out


def main():
    latin = latin_glyphs()
    glyphs = parse(UPPER, latin) + parse(LOWER, latin) + parse(EXTRA, latin)
    lines = [
        "/* Generated by tools/gen_cyrillic_font.py, do not edit. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint16_t codepoint;",
        "    uint8_t cols[5];",
        "} font_ext_glyph_t;",
        "",
        "/* Sorted by codepoint for binary search. */",
        "static const font_ext_glyph_t font_ext[] = {",
    ]
    for ch, cols in sorted(glyphs, key=lambda g: ord(g[0])):
        hexes = ", ".join(f"0x{c:02X}" for c in cols)
        lines.append(f"    {{ 0x{ord(ch):04X}, {{ {hexes} }} }}, /* {ch} */")
    lines += ["};", ""]
    (SRC / "epd_font_cyr.h").write_text("\n".join(lines))
    print(f"{len(glyphs)} glyphs written")


if __name__ == "__main__":
    main()
